/**
 * ==============================================================================================
 * BUYWISE FRONTEND — CENTRAL API CLIENT & HTTP INTERCEPTOR
 * ==============================================================================================
 * ARCHITECTURAL DESIGN & ENGINEERING RATIONALE:
 *
 * 1. BEARER TOKEN INJECTION:
 *    - Automatically retrieves the JWT access token from localStorage and injects it into
 *      the 'Authorization: Bearer <token>' HTTP header for all outbound requests.
 *
 * 2. 401 UNAUTHORIZED INTERCEPTION & EVENT BUS:
 *    - Intercepts 401 responses, purges stale credentials, and fires a decoupled window event
 *      ('buywise:unauthorized'). This triggers redirection to the login view without coupling
 *      the HTTP client directly to the React Router DOM history instance.
 *
 * 3. MULTIPART BOUNDARY HYGIENE:
 *    - When the payload is an instance of FormData, Content-Type is intentionally omitted so the
 *      browser automatically generates the correct 'multipart/form-data; boundary=----WebKitFormBoundary...' header.
 *
 * 4. RFC 7807 ERROR RESPONSE PARSING:
 *    - Extracts structured error messages (message, error fields) generated by the Spring Boot
 *      GlobalExceptionHandler, displaying human-friendly messages rather than generic error codes.
 * ==============================================================================================
 */

const BASE_URL = '/api/v1';

class ApiClient {
  /**
   * Resolves authentication headers from browser local storage.
   */
  private getAuthHeader(): Record<string, string> {
    const token = localStorage.getItem('buywise_token');
    return token ? { Authorization: `Bearer ${token}` } : {};
  }

  /**
   * Core execution pipeline handling headers, serialization, status verification, and error parsing.
   */
  async request<T>(path: string, options: RequestInit = {}): Promise<T> {
    const url = `${BASE_URL}${path}`;
    const headers: Record<string, string> = {
      ...this.getAuthHeader(),
      ...(options.headers as Record<string, string> || {}),
    };

    // Do NOT set application/json for FormData; browser calculates multipart boundary automatically
    if (!(options.body instanceof FormData)) {
      headers['Content-Type'] = 'application/json';
    }

    const response = await fetch(url, {
      ...options,
      headers,
    });

    // Decoupled session expiration handler
    if (response.status === 401) {
      localStorage.removeItem('buywise_token');
      localStorage.removeItem('buywise_user');
      window.dispatchEvent(new CustomEvent('buywise:unauthorized'));
    }

    if (!response.ok) {
      let errorMessage = `HTTP Error ${response.status}: ${response.statusText}`;
      try {
        const errorJson = await response.json();
        if (errorJson.message) {
          errorMessage = errorJson.message;
        } else if (errorJson.error) {
          errorMessage = errorJson.error;
        }
      } catch (e) {
        // Fallback if response payload was not formatted JSON
      }
      throw new Error(errorMessage);
    }

    // 204 No Content responses have an empty body
    if (response.status === 204) {
      return {} as T;
    }

    return response.json();
  }

  get<T>(path: string): Promise<T> {
    return this.request<T>(path, { method: 'GET' });
  }

  post<T>(path: string, body?: any): Promise<T> {
    return this.request<T>(path, {
      method: 'POST',
      body: body instanceof FormData ? body : JSON.stringify(body),
    });
  }

  put<T>(path: string, body?: any): Promise<T> {
    return this.request<T>(path, {
      method: 'PUT',
      body: body instanceof FormData ? body : JSON.stringify(body),
    });
  }

  patch<T>(path: string, body?: any): Promise<T> {
    return this.request<T>(path, {
      method: 'PATCH',
      body: body ? JSON.stringify(body) : undefined,
    });
  }

  delete<T>(path: string): Promise<T> {
    return this.request<T>(path, { method: 'DELETE' });
  }

  upload<T>(path: string, formData: FormData): Promise<T> {
    return this.request<T>(path, {
      method: 'POST',
      body: formData,
    });
  }
}

export const api = new ApiClient();
