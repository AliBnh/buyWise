package com.buywise.modules.ai.service;

import com.buywise.common.exception.BusinessException;
import com.buywise.modules.ai.dto.DocumentExtractionAiResult;
import com.buywise.modules.ai.dto.ExtractedFactItem;
import com.buywise.modules.ai.dto.OfferAnalysisAiResult;
import lombok.extern.slf4j.Slf4j;
import org.springframework.stereotype.Component;

import java.math.BigDecimal;

/**
 * ==============================================================================================
 * DEFENSIVE AI GUARDRAIL — STRUCTURED OUTPUT VALIDATION
 * ==============================================================================================
 * 
 * ARCHITECTURAL DESIGN & DEFENSIVE INVARIANTS:
 * 
 * 1. THE "UNTRUSTED BOUNDARY" PATTERN:
 *    - In traditional software, input validation is applied to user HTTP requests.
 *    - In AI-augmented systems, the LLM itself is an untrusted third-party component.
 *    - Problem: LLMs frequently hallucinate missing JSON keys, generate markdown wrappers
 *      (e.g., ```json ... ```), fabricate nonexistent numbers, or return confidence scores outside [0.0, 1.0].
 *    - Solution: This validator enforces strict schema conformity and boundary invariants BEFORE any
 *      AI output is permitted to interact with domain models or persist into PostgreSQL.
 * 
 * 2. SINGLE RESPONSIBILITY PRINCIPLE (SRP):
 *    - Isolates AI schema validation and sanitization into a dedicated, reusable component.
 *    - AI providers (e.g. Groq) handle network inference; this validator handles domain safety.
 *
 * 3. GRACEFUL DEGRADATION:
 *    - If optional attributes are corrupted or missing, the validator sanitizes them with safe
 *      deterministic defaults (e.g., capping confidence score between 0.00 and 1.00) rather than
 *      throwing unhandled runtime exceptions that would degrade consumer experience.
 * ==============================================================================================
 */
@Slf4j
@Component
public class StructuredOutputValidator {

    /**
     * Validates and sanitizes structured purchase comparison results generated by the LLM.
     *
     * @param result Deserialized POJO from the LLM response
     * @throws BusinessException If critical mandatory fields (such as executive summary) are absent
     */
    public void validateOfferAnalysis(OfferAnalysisAiResult result) {
        if (result == null) {
            throw new BusinessException("AI offer analysis result was empty.");
        }
        if (result.getExecutiveSummary() == null || result.getExecutiveSummary().isBlank()) {
            throw new BusinessException("AI offer analysis missing executive summary.");
        }
        // Confidence score boundary invariant: Must be within [0.00, 1.00]
        if (result.getConfidenceScore() != null) {
            if (result.getConfidenceScore().compareTo(BigDecimal.ZERO) < 0 ||
                result.getConfidenceScore().compareTo(BigDecimal.ONE) > 0) {
                log.warn("Sanitizing out-of-range AI confidence score: {}", result.getConfidenceScore());
                result.setConfidenceScore(new BigDecimal("0.85"));
            }
        } else {
            result.setConfidenceScore(new BigDecimal("0.85"));
        }
    }

    /**
     * Validates and sanitizes structured facts extracted from uploaded receipts and invoices.
     *
     * @param result Deserialized extraction result
     */
    public void validateDocumentExtraction(DocumentExtractionAiResult result) {
        if (result == null) {
            throw new BusinessException("AI document extraction result was empty.");
        }
        if (result.getExtractedFacts() == null || result.getExtractedFacts().isEmpty()) {
            log.warn("Document extraction produced zero facts.");
            return;
        }

        for (ExtractedFactItem item : result.getExtractedFacts()) {
            if (item.getFactKey() == null || item.getFactKey().isBlank()) {
                item.setFactKey("GENERAL_NOTE");
            }
            if (item.getExtractedValue() == null) {
                item.setExtractedValue("");
            }
            if (item.getConfidenceScore() == null) {
                item.setConfidenceScore(new BigDecimal("0.80"));
            } else if (item.getConfidenceScore().compareTo(BigDecimal.ZERO) < 0 ||
                       item.getConfidenceScore().compareTo(BigDecimal.ONE) > 0) {
                item.setConfidenceScore(new BigDecimal("0.80"));
            }
        }
    }
}
